export type IconName = keyof typeof paths

/** Иконка набора; размер и цвет — из макета конкретного места */
export function Icon({
  name,
  size = 20,
  color,
  strokeWidth = 1.5,
}: {
  name: IconName
  size?: number
  color?: string
  strokeWidth?: number
}) {
  return (
    <Svg size={size} strokeWidth={strokeWidth} color={color}>
      {paths[name]}
    </Svg>
  )
}

